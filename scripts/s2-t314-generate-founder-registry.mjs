#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE_PATH = "apps/mobile/src/dev/founderDiceQuestionBank.ts";
const JSON_PATH = "config/s2-t314-founder-fixture-registry.json";
const TS_PATH = "apps/mobile/src/services/diceFounderFixtureRegistry.ts";
const source = readFileSync(SOURCE_PATH, "utf8");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");

const selected = [...source.matchAll(/\{ authoring_id: "(EN|ZH)(\d{2})", language: "(en|zh-Hant)", exact_text: "([^"]+)" \}/gu)]
  .map((match) => ({
    authoring_id: `${match[1]}${match[2]}`,
    language: match[3],
    exact_text: match[4],
    exact_text_sha256: sha256(match[4]),
  }))
  .filter((entry) => entry.authoring_id !== "ZH04");
const ordinals = { en: 0, "zh-Hant": 0 };
const entries = selected.map((entry) => {
  ordinals[entry.language] += 1;
  return {
    ...entry,
    fixture_id: `dice-founder-${entry.language === "en" ? "en" : "zh"}-${String(ordinals[entry.language]).padStart(2, "0")}`,
  };
});

if (entries.length !== 40 || entries.filter((entry) => entry.language === "en").length !== 20 || entries.filter((entry) => entry.language === "zh-Hant").length !== 20) {
  throw new Error("STOP_S2_T314_FOUNDER_REGISTRY_NOT_20_20");
}
if (entries.some((entry) => entry.authoring_id === "ZH04")) {
  throw new Error("STOP_S2_T314_EXCLUDED_ZH04_PRESENT");
}

const registryPayload = {
  schema: "s2_t314_closed_founder_fixture_registry_v1",
  source_path: SOURCE_PATH,
  source_sha256: sha256(source),
  excluded_authoring_id: "ZH04",
  excluded_exact_text_sha256: sha256("我去到澳洲應該讀書定係做嘢？"),
  fixture_total: 40,
  language_totals: { en: 20, "zh-Hant": 20 },
  runtime_request_fields: ["fixture_id"],
  fixtures: entries,
};
const payloadSha256 = sha256(`${JSON.stringify(registryPayload)}\n`);
const registry = { ...registryPayload, registry_payload_sha256: payloadSha256 };

const fixtureRows = entries.map((entry) =>
  `  { fixture_id: ${JSON.stringify(entry.fixture_id)}, authoring_id: ${JSON.stringify(entry.authoring_id)}, language: ${JSON.stringify(entry.language)}, exact_text: ${JSON.stringify(entry.exact_text)} },`
).join("\n");
const ts = `// Generated by scripts/s2-t314-generate-founder-registry.mjs.\n` +
`// Exact membership is the authority; do not replace this set with a pattern.\n` +
`export const DICE_FOUNDER_FIXTURE_REGISTRY_VERSION = "dice_founder_fixture_registry_v1" as const;\n` +
`export const DICE_FOUNDER_FIXTURE_REGISTRY_SHA256 = "${payloadSha256}" as const;\n\n` +
`export const DICE_FOUNDER_FIXTURES = Object.freeze([\n${fixtureRows}\n] as const);\n\n` +
`const DICE_FOUNDER_FIXTURES_BY_ID: ReadonlyMap<string, (typeof DICE_FOUNDER_FIXTURES)[number]> = new Map(DICE_FOUNDER_FIXTURES.map((fixture) => [fixture.fixture_id, fixture]));\n` +
`const DICE_FOUNDER_FIXTURES_BY_AUTHORING_ID: ReadonlyMap<string, (typeof DICE_FOUNDER_FIXTURES)[number]> = new Map(DICE_FOUNDER_FIXTURES.map((fixture) => [fixture.authoring_id, fixture]));\n\n` +
`export type ApprovedDiceFounderFixtureId = (typeof DICE_FOUNDER_FIXTURES)[number]["fixture_id"];\n\n` +
`export function isApprovedDiceFounderFixtureId(value: unknown): value is ApprovedDiceFounderFixtureId {\n` +
`  return typeof value === "string" && DICE_FOUNDER_FIXTURES_BY_ID.has(value);\n` +
`}\n\n` +
`export function resolveDiceFounderFixture(fixtureId: string) {\n` +
`  return DICE_FOUNDER_FIXTURES_BY_ID.get(fixtureId) ?? null;\n` +
`}\n\n` +
`export function resolveDiceFounderFixtureByAuthoringId(authoringId: string) {\n` +
`  return DICE_FOUNDER_FIXTURES_BY_AUTHORING_ID.get(authoringId) ?? null;\n` +
`}\n`;

writeFileSync(JSON_PATH, `${JSON.stringify(registry, null, 2)}\n`);
writeFileSync(TS_PATH, ts);
process.stdout.write(`${payloadSha256}\n`);
